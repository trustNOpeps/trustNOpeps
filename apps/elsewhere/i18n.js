const textSources=new WeakMap();
const attrSources=new WeakMap();
const SKIP_USER='[data-no-i18n], input, textarea, option, script, style, noscript, code';
export function localize(root=document){
  const nodeRoot=root.nodeType===9?root.body:root;
  if(!nodeRoot)return;
  const walker=document.createTreeWalker(nodeRoot,NodeFilter.SHOW_TEXT);
  const changes=[];
  while(walker.nextNode()){
    const node=walker.currentNode;
    const parent=node.parentElement;
    if(!parent||parent.closest(SKIP_USER))continue;
    const original=textSources.has(node)?textSources.get(node):node.nodeValue;
    if(!textSources.has(node))textSources.set(node,original);
    const m=original.match(/^(\s*)([\s\S]*?)(\s*)$/);
    if(!m||!m[2].trim())continue;
    const translated=dynamicTranslation(m[2]);
    const next=m[1]+translated+m[3];
    if(next!==node.nodeValue)changes.push([node,next]);
  }
  for(const [node,value] of changes)node.nodeValue=value;
  const all=[nodeRoot,...nodeRoot.querySelectorAll('*')];
  for(const el of all){
    if(!(el instanceof Element)||el.closest('[data-no-i18n]'))continue;
    for(const attr of ['placeholder','aria-label','title']){
      if(!el.hasAttribute(attr))continue;
      let src=attrSources.get(el);
      if(!src){src={};attrSources.set(el,src)}
      if(!Object.hasOwn(src,attr))src[attr]=el.getAttribute(attr);
      const next=dynamicTranslation(src[attr]);
      if(el.getAttribute(attr)!==next)el.setAttribute(attr,next);
    }
  }
  document.documentElement.lang=currentLocale==='id'?'id':'en';
  document.title=currentLocale==='id'?'ELSEWHERE — Ruang untuk membandingkan pilihan':'ELSEWHERE — A field guide to the roads not taken';
  const description=document.querySelector('meta[name="description"]');
  if(description)description.content=currentLocale==='id'?'Bandingkan pilihan, ubah prioritas, dan pahami alasan Anda. Gratis, tanpa akun, dan data tersimpan di perangkat.':'ELSEWHERE is a thoughtful decision studio. Compare paths, explore tradeoffs, and understand what changes when your priorities do.';
  document.querySelectorAll('[data-locale]').forEach(button=>{
    const active=button.dataset.locale===currentLocale;
    button.setAttribute('aria-pressed',String(active));
    button.classList.toggle('active',active);
  });
}
