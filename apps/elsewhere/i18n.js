function dynamicTranslation(str) {
  if(currentLocale==='en')return str;
  if(dictionary[str])return dictionary[str];
  let m;
  if((m=str.match(/^\+(\d+) OTHER ROUTES ↗$/)))return `+${m[1]} PILIHAN LAIN ↗`;
  if((m=str.match(/^PATH (\d+) \/ (\d+)$/)))return `OPSI ${m[1]} / ${m[2]}`;
  if((m=str.match(/^Compare route (\d+): (.+)$/)))return `Bandingkan opsi ${m[1]}: ${m[2]}`;
  if((m=str.match(/^Original emphasis: (\d+) · (.*)$/)))return `Prioritas awal: ${m[1]} · ${m[2]}`;
  if((m=str.match(/^(\d+) options · (\d+) criteria( · Current)?$/)))return `${m[1]} pilihan · ${m[2]} hal penting${m[3]?' · Sedang dibuka':''}`;
  if((m=str.match(/^(.*) · (\d+) weighted criteria$/)))return `${m[1]} · ${m[2]} hal penting`;
  if((m=str.match(/^Delete “(.+)” from this device\? This cannot be undone\.$/)))return `Hapus “${m[1]}” dari perangkat ini? Tindakan ini tidak bisa dibatalkan.`;
  if((m=str.match(/^Remove (.+)$/)))return `Hapus ${m[1]}`;
  if((m=str.match(/^Delete (.+)$/)))return `Hapus ${m[1]}`;
  if((m=str.match(/^(.+): (\d+) of 121 cases$/)))return `${m[1]}: ${m[2]} dari 121 variasi`;
  if((m=str.match(/^Tied outcomes: (\d+) of 121 cases$/)))return `Hasil seri: ${m[1]} dari 121 variasi`;
  if((m=str.match(/^(.+) rating for (.+)$/)))return `Nilai ${m[1]} untuk ${m[2]}`;
  if((m=str.match(/^(.+) at (\d+(?:\.\d+)?)% based on the criteria and scores you entered\. This is a tool for reflection, not external validation\.$/)))return `${m[1]} dengan nilai ${m[2]} berdasarkan input Anda. Gunakan sebagai bahan pertimbangan, bukan kepastian.`;
  return str;
}
